def horizon_tier_for(signal: str) -> tuple[str, dict]:
    """Pick a Horizon retainer tier by demand posture — growth signals get the
    heavier managed tier, soft signals get the lighter one so cost matches
    what the outlet can justify right now."""
    if signal in ("very_high_up", "high_up"):
        tier = "Gold"
    elif signal in ("slight_up", "neutral"):
        tier = "Silver"
    else:
        tier = "Bronze"
    return tier, HORIZON_PACKAGES[tier]
