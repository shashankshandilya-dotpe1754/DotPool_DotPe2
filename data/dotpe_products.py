def contextual_pitch(family: str, pct: float | None = None,
                     event_names: list[str] | None = None,
                     weather_note: str | None = None) -> str:
    """Build the 'why pitch this' line so it names the actual driver — which
    festival/event, how big the demand swing is, and notable weather — rather
    than a static, always-the-same description of the product. The product's
    core capability (FAMILY_REASONS) is still the payoff clause; the context
    in front of it is what changes call to call."""
    is_down = pct is not None and pct < 0
    core = (FAMILY_REASONS_SOFT.get(family) if is_down else None) or FAMILY_REASONS.get(family, "")

    if pct is None:
        mag = None
    elif pct >= 40:  mag = f"a sharp {pct:.0f}% surge"
    elif pct >= 20:  mag = f"a strong {pct:.0f}% lift"
    elif pct >= 8:   mag = f"a {pct:.0f}% lift"
    elif pct >= 3:   mag = f"a modest {pct:.0f}% uptick"
    elif pct <= -30: mag = f"a sharp {abs(pct):.0f}% drop"
    elif pct <= -15: mag = f"a {abs(pct):.0f}% dip"
    elif pct <= -5:  mag = f"a soft {abs(pct):.0f}% dip"
    else:            mag = "roughly normal demand"

    if event_names:
        names = event_names[:2]
        ev_txt = " and ".join(names)
        verb = "are" if len(names) > 1 else "is"
        driver = f"{ev_txt} {verb} driving {mag} here" if mag else f"{ev_txt} {verb} active here"
    elif mag:
        driver = f"Forecast demand here is showing {mag}"
    else:
        driver = ""

    parts = [p for p in [driver, weather_note] if p]
    context = (" — ".join(parts) + ". ") if parts else ""
    return f"{context}{core}"


